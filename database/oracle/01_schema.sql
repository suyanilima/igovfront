CREATE TABLE IGOV_SETOR (
    ID_SETOR         NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NM_SETOR         VARCHAR2(200 CHAR) NOT NULL,
    ST_ATIVO         CHAR(1 CHAR) DEFAULT 'S' NOT NULL,
    DH_CRIACAO       TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    DH_ATUALIZACAO   TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_IGOV_SETOR PRIMARY KEY (ID_SETOR),
    CONSTRAINT UK_IGOV_SETOR_NOME UNIQUE (NM_SETOR),
    CONSTRAINT CK_IGOV_SETOR_ATIVO CHECK (ST_ATIVO IN ('S', 'N'))
);

CREATE TABLE IGOV_GESTOR (
    ID_GESTOR        NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_SETOR         NUMBER(19) NOT NULL,
    NM_GESTOR        VARCHAR2(200 CHAR) NOT NULL,
    DS_EMAIL         VARCHAR2(320 CHAR) NOT NULL,
    NR_TELEFONE      VARCHAR2(30 CHAR) NOT NULL,
    ST_ATIVO         CHAR(1 CHAR) DEFAULT 'S' NOT NULL,
    DH_CRIACAO       TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    DH_ATUALIZACAO   TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_IGOV_GESTOR PRIMARY KEY (ID_GESTOR),
    CONSTRAINT FK_IGOV_GESTOR_SETOR FOREIGN KEY (ID_SETOR)
        REFERENCES IGOV_SETOR (ID_SETOR),
    CONSTRAINT CK_IGOV_GESTOR_ATIVO CHECK (ST_ATIVO IN ('S', 'N'))
);

CREATE INDEX IX_IGOV_GESTOR_SETOR ON IGOV_GESTOR (ID_SETOR);
CREATE INDEX IX_IGOV_GESTOR_EMAIL ON IGOV_GESTOR (LOWER(DS_EMAIL));

CREATE TABLE IGOV_DOCUMENTO (
    ID_DOCUMENTO       NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CD_PUBLICO         VARCHAR2(36 CHAR) NOT NULL,
    ID_GESTOR          NUMBER(19) NOT NULL,
    NM_DOCUMENTO       VARCHAR2(300 CHAR) NOT NULL,
    TP_DOCUMENTO       VARCHAR2(20 CHAR) NOT NULL,
    NR_SEI             VARCHAR2(30 CHAR),
    TP_BASE_LEGAL      VARCHAR2(30 CHAR) NOT NULL,
    NR_BASE_LEGAL      VARCHAR2(50 CHAR),
    DT_VIGENCIA        DATE,
    QT_MESES_VALIDADE  NUMBER(2),
    DT_VENCIMENTO      DATE GENERATED ALWAYS AS
        (ADD_MONTHS(DT_VIGENCIA, QT_MESES_VALIDADE)) VIRTUAL,
    DS_DOCUMENTO       VARCHAR2(2000 CHAR) NOT NULL,
    DH_CRIACAO         TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    DH_ATUALIZACAO     TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_IGOV_DOCUMENTO PRIMARY KEY (ID_DOCUMENTO),
    CONSTRAINT UK_IGOV_DOC_PUBLICO UNIQUE (CD_PUBLICO),
    CONSTRAINT UK_IGOV_DOC_SEI UNIQUE (NR_SEI),
    CONSTRAINT CK_IGOV_DOC_SEI_NUM CHECK (REGEXP_LIKE(NR_SEI, '^[0-9]+$')),
    CONSTRAINT FK_IGOV_DOC_GESTOR FOREIGN KEY (ID_GESTOR)
        REFERENCES IGOV_GESTOR (ID_GESTOR),
    CONSTRAINT CK_IGOV_DOC_TIPO CHECK
        (TP_DOCUMENTO IN ('PROJETO', 'PLANO', 'PLANILHA', 'PROCESSO', 'NORMATIVO', 'SEM_NORMATIVO')),
    CONSTRAINT CK_IGOV_DOC_BASE CHECK
        (TP_BASE_LEGAL IN ('PORTARIA', 'REGIMENTO_INTERNO', 'RESOLUCAO', 'SEM_NORMATIVO')),
    CONSTRAINT CK_IGOV_DOC_VALIDADE CHECK (
        (TP_DOCUMENTO = 'SEM_NORMATIVO' AND NR_SEI IS NULL AND DT_VIGENCIA IS NULL AND QT_MESES_VALIDADE IS NULL)
        OR
        (TP_DOCUMENTO <> 'SEM_NORMATIVO' AND NR_SEI IS NOT NULL AND DT_VIGENCIA IS NOT NULL AND QT_MESES_VALIDADE BETWEEN 12 AND 1188 AND MOD(QT_MESES_VALIDADE, 12) = 0)
    ),
    CONSTRAINT CK_IGOV_DOC_BASE_NUM CHECK (
        (TP_BASE_LEGAL = 'SEM_NORMATIVO' AND NR_BASE_LEGAL IS NULL)
        OR
        (TP_BASE_LEGAL <> 'SEM_NORMATIVO' AND NR_BASE_LEGAL IS NOT NULL)
    )
);

CREATE INDEX IX_IGOV_DOC_GESTOR ON IGOV_DOCUMENTO (ID_GESTOR);
CREATE INDEX IX_IGOV_DOC_VENCIMENTO ON IGOV_DOCUMENTO (DT_VENCIMENTO);
CREATE INDEX IX_IGOV_DOC_TIPO ON IGOV_DOCUMENTO (TP_DOCUMENTO);

CREATE TABLE IGOV_HIST_DOCUMENTO (
    ID_HISTORICO       NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_DOCUMENTO       NUMBER(19) NOT NULL,
    TP_EVENTO          VARCHAR2(20 CHAR) NOT NULL,
    DS_EVENTO          VARCHAR2(2000 CHAR) NOT NULL,
    NM_RESPONSAVEL     VARCHAR2(200 CHAR),
    DH_EVENTO          TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_IGOV_HIST_DOC PRIMARY KEY (ID_HISTORICO),
    CONSTRAINT FK_IGOV_HIST_DOC FOREIGN KEY (ID_DOCUMENTO)
        REFERENCES IGOV_DOCUMENTO (ID_DOCUMENTO),
    CONSTRAINT CK_IGOV_HIST_TIPO CHECK
        (TP_EVENTO IN ('CRIACAO', 'EDICAO', 'RENOVACAO'))
);

CREATE INDEX IX_IGOV_HIST_DOC ON IGOV_HIST_DOCUMENTO (ID_DOCUMENTO, DH_EVENTO);

-- Situação dinâmica: evita persistir um status que envelhece com o tempo.
CREATE OR REPLACE VIEW VW_IGOV_DOCUMENTO_STATUS AS
SELECT
    D.ID_DOCUMENTO,
    D.CD_PUBLICO,
    D.NM_DOCUMENTO,
    D.TP_DOCUMENTO,
    D.NR_SEI,
    D.DT_VIGENCIA,
    D.QT_MESES_VALIDADE,
    D.DT_VENCIMENTO,
    D.ID_GESTOR,
    CASE
        WHEN D.TP_DOCUMENTO = 'SEM_NORMATIVO' THEN NULL
        WHEN D.DT_VENCIMENTO < TRUNC(SYSDATE) THEN 'VENCIDO'
        WHEN TRUNC(SYSDATE) >= ADD_MONTHS(
            D.DT_VENCIMENTO,
            CASE WHEN D.QT_MESES_VALIDADE = 6 THEN -3 ELSE -6 END
        ) THEN 'A_VENCER'
        ELSE 'VIGENTE'
    END AS ST_DOCUMENTO
FROM IGOV_DOCUMENTO D;

COMMENT ON TABLE IGOV_DOCUMENTO IS 'Documentos acompanhados pelo Igov Controle';
COMMENT ON COLUMN IGOV_DOCUMENTO.CD_PUBLICO IS 'UUID exposto à aplicação e integrações';
COMMENT ON COLUMN IGOV_DOCUMENTO.DT_VIGENCIA IS 'Início da vigência ou data da última renovação';
COMMENT ON COLUMN IGOV_DOCUMENTO.DT_VENCIMENTO IS 'Data virtual calculada pela vigência e prazo em meses';
COMMENT ON VIEW VW_IGOV_DOCUMENTO_STATUS IS 'Documentos com situação calculada na data da consulta';

